"""Калькулятор №1: последовательный.

Без функций и циклов: ввели два числа и операцию, посчитали, вывели.
"""

a = float(input("Первое число: ").replace(",", "."))
op = input("Операция (+ - * / ** % //): ").strip()
b = float(input("Второе число: ").replace(",", "."))

if op == "+":
    print("Результат:", a + b)
elif op == "-":
    print("Результат:", a - b)
elif op == "*":
    print("Результат:", a * b)
elif op == "/":
    if b == 0:
        print("Ошибка: деление на ноль.")
    else:
        print("Результат:", a / b)
elif op == "**":
    print("Результат:", a ** b)
elif op == "%":
    if b == 0:
        print("Ошибка: деление на ноль.")
    else:
        print("Результат:", a % b)
elif op == "//":
    if b == 0:
        print("Ошибка: деление на ноль.")
    else:
        print("Результат:", a // b)
else:
    print("Неизвестная операция.")
